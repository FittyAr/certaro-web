"""Regenerate the site's release data from Certaro's CHANGELOG.md.

    python tools/changelog/sync.py [--certaro PATH] [--check]

CHANGELOG.md in the Certaro repository is the single source of truth for versions. This script
writes `js/releases.js` (the `RELEASES` list used by the changelog page and the version shown in
the footers) and rewrites the static fallbacks marked with `data-app-version` in the HTML pages
and the `softwareVersion` of the JSON-LD block, so the site never shows a stale version.

The bilingual, condensed wording of each release lives in `tools/changelog/i18n.json`, keyed by
version. A release without an entry there is published with the public groups of CHANGELOG.md
(Added, Changed, Fixed, Removed, Deprecated, Security) in English for both languages, and the
script prints a reminder to add the Spanish summary.

--check exits with status 1 when any generated file is out of date (nothing is written).
"""
import argparse
import json
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parents[2]
PUBLIC_GROUPS = ("Added", "Changed", "Fixed", "Removed", "Deprecated", "Security")
HEADING = re.compile(r"^##\s*\[([^\]]+)\](?:\s*-\s*(\d{4}-\d{2}-\d{2}))?", re.M)
PAGES = ("index.html", "changelog.html")


def parse_changelog(text: str) -> list[dict]:
    """Releases in file order (newest first), skipping [Unreleased]."""
    marks = list(HEADING.finditer(text))
    releases = []
    for i, m in enumerate(marks):
        version, date = m.group(1).strip(), m.group(2)
        if version.lower() == "unreleased":
            continue
        if not re.fullmatch(r"\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?", version):
            sys.exit(f"CHANGELOG.md: heading [{version}] is not semver")
        if not date:
            sys.exit(f"CHANGELOG.md: release {version} has no date (## [x.y.z] - YYYY-MM-DD)")
        body = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)]
        releases.append({"version": version, "date": date, "groups": parse_groups(body)})
    if not releases:
        sys.exit("CHANGELOG.md: no released version found")
    return releases


def parse_groups(body: str) -> list[dict]:
    """Public `### Group` sections; nested bullets are folded into their parent item."""
    groups = []
    for section in re.split(r"^###\s+", body, flags=re.M)[1:]:
        title, _, content = section.partition("\n")
        title = title.strip()
        if title not in PUBLIC_GROUPS:
            continue
        items = []
        for line in content.splitlines():
            top = re.match(r"^- (.*)", line)
            sub = re.match(r"^\s{2,}- (.*)", line)
            if top:
                items.append([top.group(1).strip()])
            elif sub and items:
                items[-1].append(sub.group(1).strip())
        texts = []
        for head, *rest in items:
            if rest:
                head = f"{head.rstrip(':')}: " + "; ".join(r.rstrip(".") for r in rest) + "."
            texts.append(head)
        if texts:
            groups.append({"type": title, "en": texts, "es": texts})
    return groups


def build(releases: list[dict], curated: dict) -> tuple[list[dict], list[str]]:
    missing = []
    out = []
    for r in releases:
        entry = curated.get(r["version"])
        if entry:
            groups = entry["groups"]
        else:
            groups = r["groups"]
            missing.append(r["version"])
        out.append({"version": r["version"], "date": r["date"], "groups": groups})
    return out, missing


def render_js(releases: list[dict]) -> str:
    data = json.dumps(releases, ensure_ascii=False, indent=2)
    return (
        "// GENERATED by tools/changelog/sync.py from Certaro's CHANGELOG.md. Do not edit by hand:\n"
        "// change CHANGELOG.md (versions, dates) or tools/changelog/i18n.json (wording) and re-run.\n"
        f"const RELEASES = {data};\n\n"
        "// The released version shown by the site: always the newest entry of RELEASES.\n"
        "const CERTARO_VERSION = RELEASES[0].version;\n\n"
        "document.addEventListener(\"DOMContentLoaded\", () => {\n"
        "  document.querySelectorAll(\"[data-app-version]\").forEach((el) => {\n"
        "    el.textContent = \"v\" + CERTARO_VERSION;\n"
        "  });\n"
        "});\n"
    )


def render_page(text: str, version: str) -> str:
    text = re.sub(r"(<[^>]*\bdata-app-version\b[^>]*>)[^<]*(<)", rf"\g<1>v{version}\2", text)
    return re.sub(r'("softwareVersion":\s*")[^"]*(")', rf"\g<1>{version}\2", text)


def read(path: Path) -> str:
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--certaro", type=Path, default=SITE.parent / "Certaro",
                        help="path to the Certaro checkout (default: ../Certaro)")
    parser.add_argument("--check", action="store_true", help="fail if the site is out of date")
    args = parser.parse_args()

    changelog = args.certaro / "CHANGELOG.md"
    if not changelog.is_file():
        sys.exit(f"{changelog} not found (pass --certaro)")
    curated = json.loads((SITE / "tools" / "changelog" / "i18n.json").read_text(encoding="utf-8"))
    releases, missing = build(parse_changelog(changelog.read_text(encoding="utf-8")), curated)
    version = releases[0]["version"]

    wanted = {SITE / "js" / "releases.js": render_js(releases)}
    for page in PAGES:
        path = SITE / page
        wanted[path] = render_page(read(path), version)

    stale = [p for p, t in wanted.items() if not p.exists() or read(p) != t]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(SITE)}", file=sys.stderr)
        if stale:
            sys.exit("run: python tools/changelog/sync.py")
        print(f"site release data matches CHANGELOG.md: v{version}")
        return

    for p in stale:
        p.write_text(wanted[p], encoding="utf-8", newline="\n")
        print(f"updated {p.relative_to(SITE)}")
    for v in missing:
        print(f"note: no Spanish summary for {v} in tools/changelog/i18n.json; "
              "published the English CHANGELOG text for both languages", file=sys.stderr)
    print(f"site version: v{version}")


if __name__ == "__main__":
    main()
